const INTL_LOCALE: Record<Locale, string> = { pt: "pt-BR", en: "en-US", es: "es-ES" };

export function formatPreco(valor: number, locale: Locale): string {
  return new Intl.NumberFormat(INTL_LOCALE[locale], { style: "currency", currency: "BRL", maximumFractionDigits: valor % 1 === 0 ? 0 : 2 }).format(valor);
}

export function formatData(iso: string, locale: Locale): string {
  return new Intl.DateTimeFormat(INTL_LOCALE[locale], { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(iso));
}
